def ok_token(w: str) -> bool:
    if not w or len(w) < 2 or len(w) > 11:
        return False
    if any("a" <= ch <= "z" for ch in w):
        return False
    if "-" in w or " " in w:
        return False
    if w.endswith(("ый", "ий", "ая", "ое", "ые", "ие", "ой", "тся", "ться")):
        return False
    if is_diminutive(w) or is_inflected(w):
        return False
    if not re.fullmatch(r"[а-яё]+", w):
        return False
    if w not in _ABSTRACT_OK and _ABSTRACT.search(w):
        return False
    return True


def is_lemma_noun(w: str) -> bool:
    """Строго: есть разбор NOUN+nomn+sing, слово = лемма, не имя/гео."""
    ok = False
    for p in morph.parse(w)[:4]:
        tag = p.tag
        if "NOUN" not in tag:
            continue
        if "Name" in tag or "Surn" in tag or "Patr" in tag or "Geox" in tag:
            return False
        if "Fixd" in tag and len(w) <= 6:
            # макото и пр. заимствования без склонения
            return False
        if "nomn" in tag and "sing" in tag:
            nf = p.normal_form
            if nf == w or nf.replace("ё", "е") == w.replace("ё", "е"):
                ok = True
    return ok


def categorize(w: str) -> str | None:
    best: str | None = None
    best_len = 0
    for cat, hints in CAT_HINTS.items():
        for h in hints:
            if len(h) < 3:
                continue
            if h in w and len(h) > best_len:
                best = cat
                best_len = len(h)
    return best


def existing_words() -> set[str]:
    if not BANK.exists():
        return set()
    return set(re.findall(r"w: '([^']+)'", BANK.read_text(encoding="utf-8")))


def load_freq_rank(limit: int = 50_000) -> dict[str, int]:
    freq_path = Path(__file__).resolve().parent / "ru_noun_freq.txt"
    if not freq_path.is_file():
        raise SystemExit(f"missing {freq_path}")
    rank: dict[str, int] = {}
    for line in freq_path.read_text(encoding="utf-8").splitlines():
        if len(rank) >= limit:
            break
        parts = line.strip().split()
        if not parts:
            continue
        w = parts[0].lower()
        if w in rank or not re.fullmatch(r"[а-яё]+", w):
            continue
        rank[w] = len(rank)
    print("freq rank", len(rank))
    return rank


def load_pymorphy_noun_lemmas() -> set[str]:
    raw: set[str] = set()
    for item in morph.dictionary.iter_known_words():
        w, tag, normal = item[0], item[1], item[2]
        if "NOUN" not in tag or "nomn" not in tag or "sing" not in tag:
            continue
        if "Name" in tag or "Surn" in tag or "Patr" in tag or "Geox" in tag:
            continue
        if "Abbr" in tag:
            continue
        wl = w.lower().strip()
        nf = normal.lower().strip()
        if wl != nf and wl.replace("ё", "е") != nf.replace("ё", "е"):
            continue
        if 2 <= len(wl) <= 12 and re.fullmatch(r"[а-яё]+", wl):
            raw.add(wl)
    print("pymorphy lemmas", len(raw))
    return raw


