def ok_token(w: str) -> bool:
    if not w or len(w) < 2 or len(w) > 22:
        return False
    if any("a" <= ch <= "z" for ch in w):
        return False
    if "-" in w or " " in w:
        return False
    if w.endswith(("ый", "ий", "ая", "ое", "ые", "ие", "ой", "тся", "ться")):
        return False
    if is_diminutive(w) or is_inflected(w):
        return False
    if not re.fullmatch(r"[а-яё]+", w):
        return False
    return True


def categorize(w: str) -> str | None:
    for cat, hints in CAT_HINTS.items():
        for h in hints:
            if h in w:
                return cat
    return None


def existing_words() -> set[str]:
    if not BANK.exists():
        return set()
    return set(re.findall(r"w: '([^']+)'", BANK.read_text(encoding="utf-8")))


def main() -> None:
    if not RUACCENT_GZ.is_file():
        raise SystemExit(f"ruaccent not found: {RUACCENT_GZ}")

    seen = existing_words()
    # baseline без word_lists: пересчитается при gen — берём из bank сейчас
    buckets: dict[str, list[str]] = defaultdict(list)
    for w in seen:
        c = categorize(w) or "nature"
        buckets[c].append(w)

    target_per = (TARGET + len(CATEGORIES) - 1) // len(CATEGORIES)
    need = max(0, TARGET - len(seen))
    print("in bank", len(seen), "need", need, "per_cat~", target_per)

    lex: dict[str, str] = json.load(gzip.open(RUACCENT_GZ, "rt", encoding="utf-8"))
    candidates = []
    for w in lex:
        wl = w.lower().strip()
        if wl in seen or not ok_token(wl):
            continue
        cat = categorize(wl)
        if not cat:
            continue
        candidates.append((wl, cat))

    candidates.sort(key=lambda t: (len(t[0]), t[0]))
    added = 0
    for wl, cat in candidates:
        if len(seen) >= TARGET:
            break
        if len(buckets[cat]) >= target_per + 120:
            continue
        seen.add(wl)
        buckets[cat].append(wl)
        added += 1

    # добор без категории → nature / city по очереди
    if len(seen) < TARGET:
        filler_cats = ["nature", "city", "home", "food", "tools"]
        idx = 0
        for w in lex:
            if len(seen) >= TARGET:
                break
            wl = w.lower().strip()
            if wl in seen or not ok_token(wl):
                continue
            cat = filler_cats[idx % len(filler_cats)]
            idx += 1
            seen.add(wl)
            buckets[cat].append(wl)
            added += 1

    OUT.mkdir(parents=True, exist_ok=True)
    # только НОВЫЕ слова в word_lists (старые уберём)
    bank_now = existing_words()
    for cat in CATEGORIES:
        words = [w for w in buckets[cat] if w not in bank_now]
        path = OUT / f"{cat}.txt"
        path.write_text(" ".join(sorted(set(words))) + ("\n" if words else ""), encoding="utf-8")
        print(cat, "extra", len(words))

    print("added_candidates", added, "projected", len(seen))


if __name__ == "__main__":
    main()