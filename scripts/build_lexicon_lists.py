# меджаргон / этнонимы / абстрактный мусор — плохо для детской игры
_BAD_TAIL = re.compile(
    r"(?:"
    r"оз$|озн$|ит$|"  # артроз, паротит — часто болезни (с whitelist ниже)
    r"изм$|ист$|"
    r"ец$|ка$|"  # ливанец / слишком много ложных — сузим
    r")$"
)
_TAIL_DISEASE = re.compile(r"(?:оз|ит)$")
_DISEASE_OK = frozenset({"бандит", "кредит", "визит", "комод", "народ", "завод", "город"})


def is_blocked(w: str) -> bool:
    if w in EXTRA_BLOCK:
        return True
    if any(s in w for s in _BAD_SUB):
        return True
    if len(w) >= 5 and _TAIL_DISEASE.search(w) and w not in _DISEASE_OK:
        # артроз, антракоз, паротит…
        if w.endswith(("оз", "озн")) or (
            w.endswith("ит") and len(w) >= 6 and w not in {"бандит", "кредит", "визит"}
        ):
            # keep common: бандит already; визит ok
            if w.endswith("оз") or (w.endswith("ит") and "ит" == w[-2:]):
                # allow: бандит, визит, кредит; block: паротит, энцефалит
                if w not in {"бандит", "визит", "кредит", "комод"}:
                    if w.endswith("оз") or w.endswith(("тит", "лит", "зит", "нит", "рит")):
                        return True
    return False


def main() -> None:
    curated_seen = existing_words()
    print("current bank words", len(curated_seen))

    buckets: dict[str, list[str]] = defaultdict(list)
    seen: set[str] = set(curated_seen)
    target_per = (TARGET + len(CATEGORIES) - 1) // len(CATEGORIES)

    from gen_word_bank import is_too_hard  # noqa: WPS433

    freq = load_freq_rank(80_000)
    lemmas = load_pymorphy_noun_lemmas()
    frequent = sorted((w for w in lemmas if w in freq), key=lambda w: freq[w])
    print("freq∩lemma", len(frequent))

    added = 0
    checked = 0
    filler = [
        "nature",
        "home",
        "city",
        "food",
        "animals",
        "tools",
        "body",
        "clothes",
        "jobs",
        "school",
        "sport",
        "kitchen",
        "transport",
        "tech",
        "fantasy",
        "party",
    ]
    fi = 0
    # большой запас: антиповтор на устройстве живёт до явного сброса кнопкой
    cat_cap = max(target_per + 400, 900)

    def try_add(wl: str, cat: str) -> bool:
        nonlocal added
        if len(seen) >= TARGET:
            return False
        if wl in seen or is_blocked(wl) or not ok_token(wl):
            return False
        if is_too_hard(wl):
            return False
        if not is_lemma_noun(wl):
            return False
        if len(buckets[cat]) >= cat_cap:
            return False
        seen.add(wl)
        buckets[cat].append(wl)
        added += 1
        return True

    for wl in frequent:
        checked += 1
        cat = categorize(wl)
        if not cat:
            # без категории — только частотные короткие (иначе лезут акт/аванс/абсурд)
            rank = freq.get(wl, 99_999)
            if rank > 14_000 or not (3 <= len(wl) <= 9):
                continue
            cat = filler[fi % len(filler)]
            fi += 1
        else:
            rank = freq.get(wl, 99_999)
            if rank > 32_000:
                continue
        try_add(wl, cat)
        if added and added % 500 == 0 and checked % 500 < 3:
            print("…", added, "kept,", checked, "checked,", len(seen), "total")

    OUT.mkdir(parents=True, exist_ok=True)
    for cat in CATEGORIES:
        words = sorted({w for w in buckets[cat] if w not in curated_seen})
        path = OUT / f"{cat}.txt"
        path.write_text((" ".join(words) + "\n") if words else "", encoding="utf-8")
        print(cat, "extra", len(words))

    print("added", added, "projected_bank", len(seen), "checked", checked)


