def ok(w: str) -> bool:
    if not w or len(w) < 2:
        return False
    if any("a" <= ch <= "z" for ch in w):
        return False
    if "-" in w:
        return False
    if w.endswith(("ый", "ий", "ая", "ое", "ые", "ие", "ой")):
        return False
    return True


