def validate(d: dict[str, str]) -> None:
    for key, value in d.items():
        if value.replace("+", "") != key:
            raise SystemExit(f"stress mismatch: {key!r} -> {value!r}")
        plus = value.find("+")
        if plus < 0 or plus + 1 >= len(value) or value[plus + 1] not in VOWELS:
            raise SystemExit(f"stress mark not before a vowel: {value!r}")


def load_existing() -> dict[str, str]:
    spec = importlib.util.spec_from_file_location("stress", STRESS_PATH)
    m = importlib.util.module_from_spec(spec)
    assert spec.loader
    spec.loader.exec_module(m)
    return dict(m.STRESS)


def bank_words() -> list[str]:
    text = BANK_PATH.read_text(encoding="utf-8")
    return re.findall(r"w: '([^']+)'", text)


def main() -> None:
    fix_extras()
    validate(EXTRA)
    existing = load_existing()
    # Prefer EXTRA over old for keys we redefine (трусы already ok)
    merged = {**existing, **EXTRA}
