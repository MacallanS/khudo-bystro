_LASK_SUFFIX = re.compile(
    r"(?:"
    r"ечка|ёчка|юшка|ушка|ишка|"
    r"ечек|очек|ушек|ишек|"
    r"ёночек|еночек|оночек|"
    r"ёнечек|енечек|"
    r"ушечк|ишечк|юшечк|"
    r"ятко|енечка|онечка"
    r")$"
)

_FAKE_CHIK = re.compile(r".{5,}[аеёиоуыэюя]чик$")

# Инфинитивы и явные глагольные хвосты (без коротких сущ.: пила, сила, бандит)
_VERB_END = re.compile(
    r"(?:"
    r"ать|ить|еть|ять|оть|уть|ыть|"
    r"ишь|ите|"
    r"ешь|ёшь|ете|ёте|"
    r"ала|али|ила|или|"
    r"ут|ют|ёт"
    r")$"
)
# прош. вр. -ал/-ил только у длинных форм (писал), не у пила/сила
_VERB_PAST_SHORT = re.compile(r"(?:ал|ил)$")

_INSTRUMENTAL_OK = frozenset({"дом", "том", "бром"})

_CASE_END = re.compile(
    r"(?:"
    r"очке|очку|очкой|очках|очкам|"
    r"ечке|ечку|ечкой|"
    r"ушке|ишке|юшке|"
    r"ами|ями|ого|его|ому|ему|"
    r"ах|ях|ам|ям|ою|ею|ью|ием|ьем|"
    r"ией|ьей|"
    r"ую|юю|ым|им|"
    r"ево|ово|ева|ова|еву|ову|евы|овы|"
    r"уй|юй|"
    r"ом|ем"
    r")$"
)

_DEVERB = re.compile(
    r"(?:нув|нул|нула|нули|нуло|вши|вшись)$"
)

# повелительные обломки (домекни, взмокни, шоркай…)
_IMPERATIVE_JUNK = re.compile(
    r"(?:кни|гни|рни|тни|лни|пни|вни|сни|дни|мни|кай|гай)$"
)

# substring-мусор из лексикона
_JUNK_MORPH = re.compile(
    r"(?:авин|овин|евин|явин|ален|елен|ялен|усен|юсен|омен|емен|усен)$"
)


def is_diminutive(word: str) -> bool:
    w = word.strip().lower()
    if not w or w in DIMINUTIVE_OK or w in _TAIL_OK:
        return False
    if _LASK_SUFFIX.search(w):
        return True
    if w.endswith("очка") and w not in DIMINUTIVE_OK:
        return True
    if _FAKE_CHIK.search(w) and w not in DIMINUTIVE_OK:
        return True
    return False


def is_inflected(word: str) -> bool:
    w = word.strip().lower()
    if len(w) < 3 or len(w) > 18:
        return True
    if w in _TAIL_OK or w in DIMINUTIVE_OK:
        return False
    if w.endswith(("ся", "сь")):
        return True
    if _DEVERB.search(w):
        return True
    if len(w) >= 6 and _IMPERATIVE_JUNK.search(w):
        return True
    if len(w) >= 6 and _JUNK_MORPH.search(w):
        return True
    # длинные -ен / -ин вне whitelist — типичный мусор (одеялен, глобусен, дипломен)
    if len(w) >= 7 and w.endswith(("лен", "сен", "мен")):
        return True
    if len(w) >= 7 and w.endswith("ин") and not w.endswith(("анин", "янин")):
        return True
    if _VERB_END.search(w) and len(w) >= 5:
        # пила/сила (4) ок; читала/писала — нет
        return True
    if len(w) >= 5 and _VERB_PAST_SHORT.search(w):
        return True
    if len(w) > 4 and w.endswith(("ах", "ях", "ов", "ев")):
        return True
    if len(w) > 5 and w.endswith(("ам", "ям")):
        return True
    if _CASE_END.search(w) and w not in _INSTRUMENTAL_OK:
        return True
    if len(w) > 5 and w.endswith(("вши", "вш", "чив", "чил", "чит", "ны", "на", "но")):
        return True
    if len(w) >= 6 and w.endswith("чи"):
        return True
    if len(w) == 4 and w.endswith("и") and w not in {"такси", "цуги"}:
        return True
    if re.search(r"(?:ела|ели|ело|ети|ету|етя|ечу|еча|уя|ива|ыва)$", w):
        return True
    if len(w) >= 5 and w.endswith(("у", "ю", "я")) and w not in {
        "кенгуру",
        "рагу",
        "какао",
        "меню",
        "желе",
        "пюре",
        "алоэ",
    }:
        return True
    if len(w) >= 5 and "й" in w and not w.endswith("й"):
        return True
    if len(w) >= 5 and w.endswith(("ке", "ку", "ки", "ках", "кам")):
        return True
    if len(w) >= 6 and w.endswith(("ака", "еке", "ики", "оке", "уке")):
        return True
    return False
